const MISSING: readonly string[] = ["11111", "10001", "10001", "10001", "10001", "10001", "11111"];

/** Glyph columns plus the one-column gap after each character. */
const ADVANCE = 6;
export const GLYPH_HEIGHT = 7;

/** Width in pixels of `text` drawn at `scale` (the gap after the last character is not counted). */
export function textWidth(text: string, scale: number): number {
  return text.length === 0 ? 0 : (text.length * ADVANCE - 1) * scale;
}

export function drawText(canvas: Canvas, text: string, x: number, y: number, scale: number, color: Rgb): void {
  let left = x;
  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char] ?? MISSING;
    glyph.forEach((row, rowIndex) => {
      for (let column = 0; column < 5; column += 1) {
        if (row[column] === "1") canvas.fillRect(left + column * scale, y + rowIndex * scale, scale, scale, color);
      }
    });
    left += ADVANCE * scale;
  }
}

/** Draws `text` with its middle at `centerX`. */
export function drawCentered(canvas: Canvas, text: string, centerX: number, y: number, scale: number, color: Rgb): void {
  drawText(canvas, text, centerX - textWidth(text, scale) / 2, y, scale, color);
}

/** Draws `text` ending at `right`. */
export function drawRight(canvas: Canvas, text: string, right: number, y: number, scale: number, color: Rgb): void {
  drawText(canvas, text, right - textWidth(text, scale), y, scale, color);
}
