/**
 * Installs the running release under Moxen's own app folder:
 *
 *   <app>/versions/<version>/   the unpacked release, as it came
 *   <app>/current               a plain text file naming the active version
 *   <app>/bin/moxen[.cmd]       the launcher, which reads `current` on every start
 *
 * It only ever runs on this machine and only from a `release` install; a source checkout is refused before
 * anything is written. It never edits a shell profile or PATH: it says how, and the person does it. This is
 * deliberately not a server command, so a paired remote client cannot reach it (`moxen self-update --install`
 * refuses `--server`).
 */
import { existsSync, readFileSync, realpathSync } from "node:fs";
import { chmod, cp, mkdir, readdir, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { appEnv, appHomeDir } from "../config.js";
import { CliError } from "../errors.js";
import { renameReplacing, writeAtomic } from "../infra/atomic.js";
import type { ReleaseOs } from "../release.js";
import { readInstall, type ReadInstallOptions } from "./install.js";

export interface AppLayout {
  readonly app: string;
  readonly versions: string;
  readonly current: string;
  /** A plain text file naming the version `current` replaced, which `--rollback` goes back to. */
  readonly previous: string;
  readonly bin: string;
}

/**
 * Where the app folder is: `<MOXEN_STORE_ROOT>/app` when that is set (tests, the smoke test), else `~/.moxen/app`.
 * The default store root is `~/.moxen/threads`; the app folder sits beside it, not inside the thread store.
 */
export function appLayout(env: NodeJS.ProcessEnv = process.env, home?: string): AppLayout {
  const root = appEnv("STORE_ROOT", env)?.trim();
  const app = root ? path.join(path.resolve(root), "app") : path.join(appHomeDir(home), "app");
  return { app, versions: path.join(app, "versions"), current: path.join(app, "current"), previous: path.join(app, "previous"), bin: path.join(app, "bin") };
}

const realPath = (target: string): string => {
  try {
    return realpathSync(target);
  } catch {
    return path.resolve(target);
  }
};

/** Whether `folder` sits directly in `versions/`. A running install's folder has its links resolved and the layout's doesn't, so both are resolved here. */
export function isInstalledFolder(folder: string, layout: AppLayout): boolean {
  return path.dirname(realPath(folder)) === realPath(layout.versions);
}

/** A version becomes a folder name, so it may not hold a separator or a `..`. */
export const SAFE_VERSION = /^[0-9A-Za-z][0-9A-Za-z.+-]*$/;

export const POSIX_LAUNCHER = "moxen";
export const WINDOWS_LAUNCHER = "moxen.cmd";

/**
 * The two launcher scripts. Both find `app/` from their own location (a symlink to the sh one is followed),
 * read `current` each start, pass every argument through untouched and exit with Bun's code. The `.cmd` uses
 * CRLF line endings, which `goto` labels need.
 */
export function launcherScripts(): { readonly posix: string; readonly windows: string } {
  const posix = `#!/bin/sh
# Moxen launcher: runs the version named by ../current. Generated by moxen self-update --install.
self=$0
while [ -h "$self" ]; do
  dir=$(dirname -- "$self")
  self=$(readlink -- "$self")
  case $self in /*) ;; *) self=$dir/$self ;; esac
done
bin=$(CDPATH= cd -- "$(dirname -- "$self")" && pwd -P) || exit 1
app=$(dirname -- "$bin")
if [ ! -f "$app/current" ]; then
  echo "moxen: no version is installed ($app/current is missing); run moxen self-update --install from a release." >&2
  exit 1
fi
version=$(tr -d '\\r\\n' < "$app/current")
entry="$app/versions/$version/dist/cli/index.js"
if [ -z "$version" ] || [ ! -f "$entry" ]; then
  echo "moxen: version '$version' named in $app/current is not installed; run moxen self-update --install from a release." >&2
  exit 1
fi
exec bun "$entry" "$@"
`;
  const windows = [
    "@echo off",
    "rem Moxen launcher: runs the version named by ..\\current. Generated by moxen self-update --install.",
    "setlocal EnableExtensions DisableDelayedExpansion",
    'set "APP=%~dp0.."',
    'if not exist "%APP%\\current" goto nocurrent',
    'set "VERSION="',
    'set /p VERSION=<"%APP%\\current"',
    "if not defined VERSION goto missing",
    'if not exist "%APP%\\versions\\%VERSION%\\dist\\cli\\index.js" goto missing',
    'bun "%APP%\\versions\\%VERSION%\\dist\\cli\\index.js" %*',
    "exit /b %ERRORLEVEL%",
    ":nocurrent",
    "echo moxen: no version is installed (current is missing); run moxen self-update --install from a release. 1>&2",
    "exit /b 1",
    ":missing",
    "echo moxen: the version named in current is not installed; run moxen self-update --install from a release. 1>&2",
    "exit /b 1",
    "",
  ].join("\r\n");
  return { posix, windows };
}

/** How to put `bin` on PATH for this platform. We print it; we never run it. */
export function pathHint(os: ReleaseOs | string, bin: string): string {
  if (os === "windows") {
    return `Add ${bin} to your PATH (PowerShell, then open a new terminal):\n  [Environment]::SetEnvironmentVariable("Path", [Environment]::GetEnvironmentVariable("Path", "User") + ";${bin}", "User")`;
  }
  return `Add ${bin} to your PATH, for example in ~/.zshrc or ~/.bashrc (then open a new terminal):\n  export PATH="${bin}:$PATH"`;
}

export interface InstallResult {
  readonly version: string;
  /** `<app>/versions/<version>`. */
  readonly folder: string;
  readonly current: string;
  readonly launcher: string;
  readonly bin: string;
  /** The version folder was already there and left as it was. */
  readonly alreadyInstalled: boolean;
  readonly pathHint: string;
}

export interface InstallOptions extends ReadInstallOptions {
  readonly layout?: AppLayout;
  readonly env?: NodeJS.ProcessEnv;
}

export const TEMP_PREFIX = ".tmp-";

async function writeLauncher(file: string, text: string): Promise<void> {
  const tmp = `${file}.tmp.${process.pid}.${Date.now()}`;
  await writeFile(tmp, text, { encoding: "utf8", mode: 0o755 });
  await chmod(tmp, 0o755);
  await renameReplacing(tmp, file);
}

export async function installRelease(options: InstallOptions = {}): Promise<InstallResult> {
  // First, before any write: only a release install may be installed.
  const install = readInstall(options);
  if (install.kind !== "release" || install.folder === null || install.target === null) {
    throw new CliError(
      "SELF_UPDATE_SOURCE_INSTALL",
      "This Moxen is a source checkout, which moxen never installs or updates. Run moxen self-update --install from an unpacked release archive.",
      { exitCode: 1 },
    );
  }
  if (!SAFE_VERSION.test(install.version)) {
    throw new CliError("SELF_UPDATE_BAD_VERSION", `The release version "${install.version}" is not a valid folder name.`, { exitCode: 1 });
  }
  const layout = options.layout ?? appLayout(options.env);
  const target = path.join(layout.versions, install.version);
  const alreadyInside = isInstalledFolder(install.folder, layout);
  const exists = existsSync(target);

  await mkdir(layout.versions, { recursive: true });
  if (!alreadyInside && !exists) {
    // A copy that was cut short leaves only a temp folder, which never looks installed.
    for (const entry of await readdir(layout.versions)) {
      if (entry.startsWith(TEMP_PREFIX)) await rm(path.join(layout.versions, entry), { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
    }
    const temp = path.join(layout.versions, `${TEMP_PREFIX}${install.version}-${process.pid}-${Date.now()}`);
    try {
      await cp(install.folder, temp, { recursive: true, errorOnExist: true });
      await rename(temp, target);
    } catch (error) {
      await rm(temp, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
      throw error;
    }
  }

  const windows = install.target.os === "windows";
  const launcher = path.join(layout.bin, windows ? WINDOWS_LAUNCHER : POSIX_LAUNCHER);
  // Only change `current` when it differs, so a repeat install writes nothing it does not need to.
  const stored = existsSync(layout.current) ? readFileSync(layout.current, "utf8") : null;
  if (stored !== `${install.version}\n`) await writeAtomic(layout.current, `${install.version}\n`);
  await mkdir(layout.bin, { recursive: true });
  const scripts = launcherScripts();
  const text = windows ? scripts.windows : scripts.posix;
  if (!existsSync(launcher) || readFileSync(launcher, "utf8") !== text) await writeLauncher(launcher, text);

  return {
    version: install.version,
    folder: target,
    current: layout.current,
    launcher,
    bin: layout.bin,
    alreadyInstalled: alreadyInside || exists,
    pathHint: pathHint(install.target.os, layout.bin),
  };
}
