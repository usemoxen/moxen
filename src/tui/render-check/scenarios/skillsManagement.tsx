import path from "node:path";
import { act } from "react";
import { SkillsPanel } from "../../features/settings/skillspanel.js";
import { skillsClient } from "../skillsfixture.js";
import { testRender } from "../testrender.js";
import { fail } from "../helpers.js";

export async function runSkillsManagement(): Promise<void> {
  const { api, writes } = skillsClient();
  let closed = false;
  let setup!: Awaited<ReturnType<typeof testRender>>;
  await act(async () => {
    setup = await testRender(<SkillsPanel client={api} width={88} onClose={() => { closed = true; }} />, { width: 90, height: 32, exitOnCtrlC: false, kittyKeyboard: true });
  });
  const settle = async () => { await act(async () => {}); await setup.flush(); };
  const key = async (name: string) => { await act(async () => (name === "down" ? setup.mockInput.pressArrow("down") : setup.mockInput.pressKey(name))); await settle(); };
  await settle();
  let frame = setup.captureCharFrame();
  if (!frame.includes("diagrams") || !frame.includes("review") || !frame.includes("team-style")) fail("Skills management lost an origin or a disabled skill.");
  console.log("--- skills management ---"); console.log(frame);
  await key(" ");
  if (!writes.some((command) => command.type === "skills.enabled.set" && command.enabled === false)) fail("Space did not disable the selected skill.");
  // The provider choice: the MCP checklist's editor, one row per provider, applied at once.
  const providerSets = () => writes.filter((command) => command.type === "skills.providers.set");
  const clickRow = async (label: string) => {
    const rows = setup.captureCharFrame().split("\n");
    const row = rows.findIndex((line) => line.includes(label));
    if (row < 0) fail(`The skills page has no "${label}" to click.`);
    await act(async () => setup.mockMouse.click(rows[row]!.indexOf(label) + 1, row)); await settle();
  };
  frame = setup.captureCharFrame();
  if (!frame.includes("Offered to every provider") || !frame.includes("Providers") || frame.includes("[ ")) fail("The skills page lost its provider line or still draws bracket buttons.");
  if (!frame.includes("claude · disabled · Claude Code, Codex")) fail("A restricted skill's list row does not name its providers.");
  await key("p");
  frame = setup.captureCharFrame();
  console.log("--- skills providers ---"); console.log(frame);
  if (!frame.includes("Providers for diagrams") || !frame.includes("4 of 4 on") || !frame.includes("Moxen Harness")) fail("The provider choice did not open for the selected skill with every provider on.");
  if (closed) fail("Opening the provider choice closed settings.");
  await key("down"); await key(" ");
  const first = providerSets().at(-1);
  if (first?.type !== "skills.providers.set" || first.folder !== "diagrams" || first.providers.join() !== "claude,opencode,harness") fail("Unticking Codex with the keyboard did not send the other three providers.");
  if (!setup.captureCharFrame().includes("3 of 4 on")) fail("The provider choice did not show Codex off.");
  await clickRow("OpenCode");
  const second = providerSets().at(-1);
  if (second?.type !== "skills.providers.set" || second.providers.join() !== "claude,harness") fail("Clicking OpenCode did not untick it.");
  const before = providerSets().length;
  await key("n");
  if (providerSets().length !== before || !setup.captureCharFrame().includes("at least one provider")) fail("Switching every provider off was sent to the server instead of refused.");
  await key("a");
  const all = providerSets().at(-1);
  if (all?.type !== "skills.providers.set" || all.providers.length !== 0) fail("Turning every provider on did not send the empty list (every provider).");
  await act(async () => setup.mockInput.pressEscape()); await settle();
  if (closed || setup.captureCharFrame().includes("Providers for diagrams")) fail("Escape in the provider choice did not go back to the skill, or closed settings.");
  await clickRow("Providers");
  await key(" ");
  await key("down"); await key("down"); await key("down"); await key(" ");
  const last = providerSets().at(-1);
  if (last?.type !== "skills.providers.set" || last.providers.join() !== "codex,opencode") fail("The Providers button did not open the choice, or the ticks were wrong.");
  await act(async () => setup.mockInput.pressEscape()); await settle();
  frame = setup.captureCharFrame();
  console.log("--- skills restricted ---"); console.log(frame);
  if (!frame.includes("Offered to Codex, OpenCode") || !frame.includes("agents · disabled · Codex, OpenCode")) fail("The skill list did not show the providers it is now offered to.");
  await key("e");
  console.log("--- skills edit ---"); console.log(setup.captureCharFrame());
  if (!setup.captureCharFrame().includes("shift+enter")) fail("Editing did not load SKILL.md.");
  await act(async () => setup.mockInput.pressEscape()); await settle();
  if (closed) fail("Escape closed settings instead of cancelling a skill edit.");
  if (setup.captureCharFrame().includes("shift+enter")) fail("Escape did not cancel the skill edit.");
  await key("a");
  console.log("--- skills import ---"); console.log(setup.captureCharFrame());
  const from = path.resolve("incoming-skill");
  for (const char of from) await act(async () => setup.mockInput.pressKey(char));
  await act(async () => setup.mockInput.pressEnter()); await settle();
  if (!writes.some((command) => command.type === "skills.import" && command.from === from && command.source === "agents")) fail("Import did not send the selected folder to the server.");
  await key("d");
  await key("n");
  if (writes.some((command) => command.type === "skills.remove")) fail("Cancelling removal still removed a skill.");
  await key("d"); await key("y");
  if (!writes.some((command) => command.type === "skills.remove" && command.folder === "diagrams")) fail("Confirmed removal did not reach the server.");
  await key("s");
  frame = setup.captureCharFrame();
  const rows = frame.split("\n");
  const row = rows.findIndex((line) => line.includes("Demo project"));
  if (row < 0) fail("The skills scope picker did not list projects.");
  await act(async () => setup.mockMouse.click(rows[row]!.indexOf("Demo project") + 1, row)); await settle();
  if (!setup.captureCharFrame().includes("No skills in this scope")) fail("Project skills were not kept separate from user skills.");
  await act(async () => setup.renderer.destroy());
}
